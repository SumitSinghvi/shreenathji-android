import com.shreenathji.sales.data.local.entities.OrderWithItems
import com.shreenathji.sales.ui.util.challan.PdfChallanGenerator
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream

object OrderChallanPrintHelper {

    /**
     * Prints the exact same vector PDF generated by PdfChallanGenerator
     * via Android PrintManager.
     */
    fun printChallan(context: Context, orderWithItems: OrderWithItems) {
        val hasPhotos = !orderWithItems.order.imageUrisJson.isNullOrBlank() ||
                orderWithItems.items.any { !it.imageUrl.isNullOrBlank() }
        if (hasPhotos) {
            Toast.makeText(context, "Preparing Challan for printing...", Toast.LENGTH_SHORT).show()
        }

        CoroutineScope(Dispatchers.IO).launch {
            try {
                val pdfFile = generatePdf(context, orderWithItems)
                withContext(Dispatchers.Main) {
                    val printManager = context.getSystemService(Context.PRINT_SERVICE) as? PrintManager ?: return@withContext
                    val jobName = "Order_Challan_${orderWithItems.order.orderNumber}"
                    val printAdapter = PdfFilePrintDocumentAdapter(pdfFile, jobName)

                    val printAttributes = PrintAttributes.Builder()
                        .setMediaSize(PrintAttributes.MediaSize.ISO_A4)
                        .setColorMode(PrintAttributes.COLOR_MODE_COLOR)
                        .setMinMargins(PrintAttributes.Margins.NO_MARGINS)
                        .build()

                    printManager.print(jobName, printAdapter, printAttributes)
                }
            } catch (e: Exception) {
                e.printStackTrace()
                withContext(Dispatchers.Main) {
                    Toast.makeText(context, "Failed to prepare print: ${e.message}", Toast.LENGTH_LONG).show()
                }
            }
        }
    }

    /**
     * Generates a real multi-page PDF file with vector challan and photo pages
     * and shares it via Intent.ACTION_SEND (application/pdf) with FileProvider.
     */
    fun shareChallanPdf(context: Context, orderWithItems: OrderWithItems) {
        val hasPhotos = !orderWithItems.order.imageUrisJson.isNullOrBlank() ||
                orderWithItems.items.any { !it.imageUrl.isNullOrBlank() }
        if (hasPhotos) {
            Toast.makeText(context, "Preparing PDF with attached photos...", Toast.LENGTH_SHORT).show()
        }

        CoroutineScope(Dispatchers.IO).launch {
            try {
                val pdfFile = generatePdf(context, orderWithItems)
                withContext(Dispatchers.Main) {
                    val contentUri = FileProvider.getUriForFile(
                        context,
                        "${context.packageName}.fileprovider",
                        pdfFile
                    )

                    val shareIntent = Intent(Intent.ACTION_SEND).apply {
                        type = "application/pdf"
                        putExtra(Intent.EXTRA_STREAM, contentUri)
                        putExtra(Intent.EXTRA_SUBJECT, "Order Challan - ${orderWithItems.order.orderNumber}")
                        putExtra(
                            Intent.EXTRA_TEXT,
                            "Shree Nath Ji - Order Challan #${orderWithItems.order.orderNumber} for ${orderWithItems.order.partyName}"
                        )
                        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                    }

                    context.startActivity(Intent.createChooser(shareIntent, "Share Order Challan PDF"))
                }
            } catch (e: Exception) {
                e.printStackTrace()
                withContext(Dispatchers.Main) {
                    Toast.makeText(context, "Failed to generate PDF: ${e.message}", Toast.LENGTH_LONG).show()
                }
            }
        }
    }

    /**
     * Native vector PDF Document rendering using Android PdfDocument
     */
    fun generatePdf(context: Context, orderWithItems: OrderWithItems): File {
        return PdfChallanGenerator.generatePdf(context, orderWithItems)
    }
}

/**
 * Streams a pre-generated PDF file into Android PrintManager's output descriptor.
 */
class PdfFilePrintDocumentAdapter(
    private val pdfFile: File,
    private val documentName: String
) : PrintDocumentAdapter() {

    override fun onLayout(
        oldAttributes: PrintAttributes?,
        newAttributes: PrintAttributes?,
        cancellationSignal: CancellationSignal?,
        callback: LayoutResultCallback?,
        extras: Bundle?
    ) {
        if (cancellationSignal?.isCanceled == true) {
            callback?.onLayoutCancelled()
            return
        }

        val info = PrintDocumentInfo.Builder(documentName)
            .setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
            .setPageCount(PrintDocumentInfo.PAGE_COUNT_UNKNOWN)
            .build()

        callback?.onLayoutFinished(info, true)
    }

    override fun onWrite(
        pages: Array<out PageRange>?,
        destination: ParcelFileDescriptor?,
        cancellationSignal: CancellationSignal?,
        callback: WriteResultCallback?
    ) {
        if (cancellationSignal?.isCanceled == true) {
            callback?.onWriteCancelled()
            return
        }

        var input: FileInputStream? = null
        var output: FileOutputStream? = null

        try {
            input = FileInputStream(pdfFile)
            output = FileOutputStream(destination?.fileDescriptor)

            val buffer = ByteArray(8192)
            var bytesRead: Int
            while (input.read(buffer).also { bytesRead = it } >= 0) {
                if (cancellationSignal?.isCanceled == true) {
                    callback?.onWriteCancelled()
                    return
                }
                output.write(buffer, 0, bytesRead)
            }

            callback?.onWriteFinished(arrayOf(PageRange.ALL_PAGES))
        } catch (e: Exception) {
            callback?.onWriteFailed(e.message)
        } finally {
            try {
                input?.close()
                output?.close()
            } catch (_: Exception) {}
        }
    }
}
